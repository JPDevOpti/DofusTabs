//! Minimal, dependency-free MD5 implementation.
//!
//! Used to derive the `Characters/<hash>` directory name from a decimal
//! character id (verified: `md5("915893715234")` ==
//! `92d60605292e2c0cd060f461d152d096`, the hash the Linux client uses under
//! `~/.config/unity3d/Ankama/Dofus/<RELEASE>/Accounts/<accountId>/Characters/`).
//! MD5 is not used for anything security-sensitive here, only to reproduce a
//! third-party naming scheme, so a small self-contained implementation
//! (rather than pulling in a crate) is fine.

